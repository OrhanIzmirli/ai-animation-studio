"""Spike: one recorded Wan Turbo run from an SDXL-pipeline keyframe, through
the benchmark runner (record under benchmarks/results, video under outputs/,
metrics through the quality store), like the E1 runs.

    python spikes/wan_bench_run.py --keyframe spikes/output/sdxl_ipadapter/x.png
        --name bench_1280b_seed43 --prompt "..." [--seconds 5] [--seed 42]

The keyframe is copied (never overwritten) to
benchmarks/references/hero01_sdxl_keyframes/<name>.png with a provenance
file that says it was generated by spikes/sdxl_ipadapter_spike.py, so the
run record's start-frame path and checksum point at something durable. The
run is recorded with run_purpose "experiment" under benchmark id
hero01_sdxl_bench_01. Nothing is deleted anywhere.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from ai_studio.benchmarking import BenchmarkLogger, BenchmarkRunner  # noqa: E402
from ai_studio.generation.backends.wan_comfyui import WanTurboComfyUIBackend  # noqa: E402
from ai_studio.generation.request import Resolution, VideoGenerationRequest  # noqa: E402
from ai_studio.paths import outputs_dir, results_dir  # noqa: E402
from ai_studio.references import make_read_only, sha256_file  # noqa: E402
from sdxl_ipadapter_spike import Monitor, available_ram_gb, vram_used_mib  # noqa: E402
from wan_video_spike import NEGATIVE, contact_sheet  # noqa: E402

BENCHMARK_ID = "hero01_sdxl_bench_01"
ASSET_SET = "hero01_sdxl_keyframes"
OUT = ROOT / "spikes/output/wan_video"


def install_keyframe(keyframe: Path, name: str) -> str:
    """Copy the keyframe into the asset set with a provenance file; returns the project-relative path."""
    folder = ROOT / "benchmarks/references" / ASSET_SET
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / f"{name}{keyframe.suffix.lower()}"
    relative = target.relative_to(ROOT).as_posix()
    digest = sha256_file(keyframe)
    if target.exists():
        if sha256_file(target) != digest:
            raise FileExistsError(f"{relative} exists with a different hash; refusing to overwrite")
        return relative
    report_path = keyframe.parent / f"report_{keyframe.stem.replace('sdxl_ipadapter_', '')}.json"
    generation = json.loads(report_path.read_text(encoding="utf-8")) if report_path.is_file() else None
    from PIL import Image

    with Image.open(keyframe) as image:
        width, height, image_format = image.width, image.height, image.format
    record = {
        "provenance_version": 1,
        "asset_set": ASSET_SET,
        "file": relative,
        "sha256": digest,
        "bytes": keyframe.stat().st_size,
        "width": width,
        "height": height,
        "format": image_format,
        "original_filename": keyframe.name,
        "origin": "generated on this machine by spikes/sdxl_ipadapter_spike.py (SDXL base + character LoRA + "
                  "IP-Adapter in the local ComfyUI); not a benchmark run, not hand-made",
        "generation": generation,
        "imported_at": datetime.now(timezone.utc).isoformat(),
    }
    sidecar = target.with_name(target.name + ".provenance.json")
    with open(keyframe, "rb") as reader, open(target, "xb") as writer:
        shutil.copyfileobj(reader, writer)
    with sidecar.open("x", encoding="utf-8") as f:
        f.write(json.dumps(record, indent=2, ensure_ascii=False) + "\n")
    for path in (target, sidecar):
        make_read_only(path)
    return relative


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--keyframe", required=True)
    parser.add_argument("--name", required=True, help="file name of the keyframe inside the asset set")
    parser.add_argument("--prompt", required=True)
    parser.add_argument("--seconds", type=float, default=5.0)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--notes", default="")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)

    report: dict = {
        "benchmark_id": BENCHMARK_ID, "seconds_requested": args.seconds, "seed": args.seed,
        "ram_available_before_gb": round(available_ram_gb(), 2), "vram_used_before_mib": vram_used_mib(),
    }
    monitor = Monitor()
    try:
        start_frame = install_keyframe(Path(args.keyframe), args.name)
        report["start_frame"] = start_frame
        request = VideoGenerationRequest(
            prompt=args.prompt, negative_prompt=NEGATIVE, duration_seconds=args.seconds,
            output_resolution=Resolution(width=1280, height=704), seed=args.seed, start_frame=start_frame,
        )
        runner = BenchmarkRunner(BenchmarkLogger(results_dir(ROOT)), outputs_dir(ROOT), root=ROOT)
        monitor.start()
        started = time.perf_counter()
        record = runner.run(
            request, WanTurboComfyUIBackend(), benchmark_id=BENCHMARK_ID, purpose="experiment",
            notes=args.notes or f"spike: Wan Turbo from an SDXL-pipeline keyframe ({args.name}); spikes/WAN_VIDEO_SPIKE.md",
        )
        report["run_seconds"] = round(time.perf_counter() - started, 1)
        report["run_id"] = record.run_id
        report["status"] = record.status
        report["record"] = str(runner.logger.path_for(BENCHMARK_ID, record.run_id).relative_to(ROOT))
        report["output_video"] = record.output_video
        report["frame_count"] = record.frame_count
        report["total_time_seconds"] = record.total_time_seconds
        report["generation_time_seconds"] = record.generation_time_seconds
        monitor.stop.set()
        # Metrics, like the E1 runs: metrics_v3.json beside the record's video.
        measured = subprocess.run(
            [sys.executable, str(ROOT / "scripts/measure_run.py"), "--benchmark", BENCHMARK_ID, "--run-id", record.run_id],
            capture_output=True, text=True, cwd=ROOT, timeout=1800,
        )
        report["measure_exit_code"] = measured.returncode
        report["measure_output"] = measured.stdout.strip().splitlines()[-25:]
        if measured.returncode != 0:
            report["measure_stderr"] = measured.stderr.strip()[-2000:]
        contact_sheet(ROOT / record.output_video, OUT / f"{BENCHMARK_ID}_{record.run_id}_contact_sheet.png")
        return 0
    except Exception as exc:  # a spike: report whatever went wrong, change nothing
        report["error"] = f"{type(exc).__name__}: {exc}"
        return 1
    finally:
        monitor.stop.set()
        report["vram_peak_mib"] = monitor.vram_peak
        report["ram_available_lowest_gb"] = None if monitor.ram_low == float("inf") else round(monitor.ram_low, 2)
        (OUT / f"report_{BENCHMARK_ID}_{report.get('run_id', 'failed')}.json").write_text(
            json.dumps(report, indent=2), encoding="utf-8",
        )
        print(json.dumps(report, indent=2))


if __name__ == "__main__":
    sys.exit(main())
